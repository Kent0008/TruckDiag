def lookup_dtc_info(
    code_raw: str,
    spn: Optional[int] = None,
    fmi: Optional[int] = None,
    source_ecu: Optional[str] = None
) -> DtcInfo:
    """
    Возвращает исчерпывающую русскоязычную расшифровку неисправности.
    Если точной проверенной расшифровки нет, честно возвращает статус
    'Расшифровка не найдена. Требуются дополнительные данные'.
    """
    # 1. Поиск по SPN + FMI
    if spn is not None and fmi is not None:
        key = f"SPN_{spn}_FMI_{fmi}"
        if key in VERIFIED_DTC_CATALOG:
            data = VERIFIED_DTC_CATALOG[key]
            return DtcInfo(**data)

    # 2. Поиск по коду (P0401 и др.)
    for key, data in VERIFIED_DTC_CATALOG.items():
        if key in code_raw or data["code"].startswith(code_raw):
            return DtcInfo(**data)

    # 3. Честный fallback для неподтверждённых/неизвестных кодов
    ecu_str = source_ecu or "Неизвестный блок управления"
    spn_part = f"SPN {spn}" if spn is not None else ""
    fmi_part = f"FMI {fmi}" if fmi is not None else ""
    code_display = f"{spn_part} {fmi_part}".strip() or code_raw

    return DtcInfo(
        code=code_raw,
        spn=spn,
        fmi=fmi,
        source_ecu=ecu_str,
        user_title=f"Неисправность: {code_display}",
        explanation="Расшифровка не найдена. Требуются дополнительные данные от производителя или сервисного диагностического сканера.",
        symptoms="Симптомы зависят от конкретной подсистемы, к которой относится блок " + ecu_str + ".",
        self_check_steps="1. Обратите внимание на контрольные лампы панели приборов (STOP / Warning).\n2. Проверьте поведение тягача: тягу, посторонние звуки, вибрацию, утечки жидкостей под автомобилем.",
        specialist_steps="Требуется углублённая компьютерная диагностика с дилерским диагностическим комплексом (Scania SDP3 или Volvo Tech Tool) для чтения расширенных данных стоп-кадра (Freeze Frame).",
        urgency="Срочность не определена",
        driving_recommendation="Степень опасности не определена. Если горит красный сигнал STOP или мигает аварийная индикация — движение прекратить. Если только жёлтый индикатор — двигаться с повышенной осторожностью до ближайшего сервиса.",
        fidelity="Требуются дополнительные данные (Не подтверждено)"
    )


